begin;

create table if not exists public.accounts (
    account_id integer generated by default as identity primary key,
    account_username varchar(100) not null,
    account_password varchar(255) not null,
    account_role varchar(20) not null default 'client',
    account_email varchar(255),
    full_name varchar(150),
    phone varchar(30),
    created_at timestamptz not null default current_timestamp,
    constraint uq_accounts_username unique (account_username),
    constraint uq_accounts_email unique (account_email),
    constraint chk_accounts_role check (account_role in ('admin', 'client'))
);

create table if not exists public.services (
    service_id integer generated by default as identity primary key,
    service_name varchar(150) not null,
    service_description text,
    price numeric(10, 2) not null,
    duration_minutes integer not null,
    created_at timestamptz not null default current_timestamp,
    constraint chk_services_price check (price >= 0),
    constraint chk_services_duration check (duration_minutes > 0)
);

create table if not exists public.bookings (
    booking_id integer generated by default as identity primary key,
    client_id integer not null,
    service_id integer not null,
    customer_name varchar(150) not null,
    customer_phone varchar(30),
    vehicle_type varchar(100) not null,
    booking_date date not null,
    booking_time time not null,
    notes text,
    payment_method varchar(30) not null default 'cash',
    payment_status varchar(20) not null default 'unpaid',
    payment_reference varchar(100),
    paid_at timestamptz,
    status varchar(20) not null default 'pending',
    created_at timestamptz not null default current_timestamp,
    updated_at timestamptz not null default current_timestamp,
    constraint fk_bookings_client
        foreign key (client_id) references public.accounts (account_id)
        on delete cascade on update cascade,
    constraint fk_bookings_service
        foreign key (service_id) references public.services (service_id)
        on delete cascade on update cascade,
    constraint chk_bookings_payment_method
        check (payment_method in ('cash', 'gcash', 'maya', 'bank_transfer')),
    constraint chk_bookings_payment_status
        check (payment_status in ('unpaid', 'paid')),
    constraint chk_bookings_status
        check (status in ('pending', 'confirmed', 'in_progress', 'completed', 'cancelled'))
);

create index if not exists idx_bookings_client_id on public.bookings (client_id);
create index if not exists idx_bookings_service_id on public.bookings (service_id);
create index if not exists idx_bookings_status on public.bookings (status);
create index if not exists idx_bookings_date on public.bookings (booking_date);

create or replace function public.set_updated_at()
returns trigger as $$
begin
    new.updated_at = current_timestamp;
    return new;
end;
$$ language plpgsql;

