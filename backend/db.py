class DictCursor:
    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, sql, params=()):
        if isinstance(sql, str):
            sql = sql.replace("%s", "?")
        if params is None:
            params = ()
        return self._cursor.execute(sql, params)

    def executemany(self, sql, seq_of_params):
        if isinstance(sql, str):
            sql = sql.replace("%s", "?")
        return self._cursor.executemany(sql, seq_of_params)

    def fetchone(self):
        row = self._cursor.fetchone()
        if row is None:
            return None
        if isinstance(row, sqlite3.Row):
            return dict(row)
        return row

    def fetchall(self):
        rows = self._cursor.fetchall()
        if not rows:
            return []
        if rows and isinstance(rows[0], sqlite3.Row):
            return [dict(row) for row in rows]
        return rows

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def close(self):
        return self._cursor.close()

    def __enter__(self):
        return self

    def __exit__(self, exc_type, exc_value, traceback):
        self.close()
        return False


class SQLiteConnection:
    def __init__(self, conn):
        self._conn = conn

    def cursor(self):
        return DictCursor(self._conn.cursor())

    def commit(self):
        return self._conn.commit()

    def rollback(self):
        return self._conn.rollback()

    def close(self):
        return self._conn.close()


def get_db_connection():
    if not Config.DATABASE_URL:
        raise RuntimeError(
            "DATABASE_URL is not configured. Add your Supabase PostgreSQL "
            "connection string to the environment."
        )
    if Config.DATABASE_URL.startswith("sqlite:"):
        parsed = urlparse(Config.DATABASE_URL)
        db_path = parsed.path or ""
        if db_path.startswith("//"):
            db_path = db_path[1:]
        if os.name == "nt" and db_path.startswith("/") and len(db_path) > 2:
            db_path = db_path.lstrip("/")
        if not db_path or db_path == "/":
            db_path = os.path.join(
                os.path.dirname(os.path.dirname(__file__)),
                "instance",
                "carwash.db",
            )
        os.makedirs(os.path.dirname(os.path.abspath(db_path)), exist_ok=True)
        conn = sqlite3.connect(db_path)
        conn.row_factory = sqlite3.Row
        conn.execute("PRAGMA foreign_keys = ON")
        return SQLiteConnection(conn)
    if psycopg is None:
        raise RuntimeError("psycopg is not installed")
    return psycopg.connect(
        Config.DATABASE_URL,
        row_factory=dict_row,
        prepare_threshold=None,
        connect_timeout=10,
    )


