def init_db():
    connection = get_db_connection()
    try:
        _initialize(connection)
    finally:
        connection.close()


def ensure_db_initialized():
    """Initialize the schema once per process, retrying after failures."""
    global _initialized
    if _initialized:
        return
    with _init_lock:
        if _initialized:
            return
        init_db()
        _initialized = True
